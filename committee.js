// ============================================================
// PHOTO PATH
// ============================================================

function getMemberPhoto(photo) {

    if (!photo) {
        return "assets/images/logo.png";
    }

    return photo;
}


// ============================================================
// CREATE MEMBER CARD
// ============================================================

function createMemberCard(member) {

    const card = document.createElement("div");

    card.className = "member-card";
    card.setAttribute("tabindex", "0");

    card.innerHTML = `
        <div class="member-photo">

            <img
                src="${getMemberPhoto(member.photo)}"
                alt="${member.name || "Committee Member"}"
                loading="lazy"
                onerror="this.onerror=null;this.src='assets/images/logo.png';"
            >

        </div>

        <div class="member-info">

            <h3>
                ${member.name || "Member Name"}
            </h3>

            <p class="designation">
                ${member.designation || "Member"}
            </p>

            <div class="member-card-details">

                ${
                    member.fatherName
                        ? `
                        <div class="member-card-detail">
                            <span>Father's Name</span>
                            <strong>${member.fatherName}</strong>
                        </div>
                        `
                        : ""
                }

                ${
                    member.registrationNo
                        ? `
                        <div class="member-card-detail">
                            <span>Registration No.</span>
                            <strong>${member.registrationNo}</strong>
                        </div>
                        `
                        : ""
                }

                ${
                    member.bloodGroup
                        ? `
                        <div class="member-card-detail">
                            <span>Blood Group</span>
                            <strong>${member.bloodGroup}</strong>
                        </div>
                        `
                        : ""
                }

                ${
                    member.dateOfJoining
                        ? `
                        <div class="member-card-detail">
                            <span>Date of Joining</span>
                            <strong>${member.dateOfJoining}</strong>
                        </div>
                        `
                        : ""
                }

                ${
                    member.membershipStatus
                        ? `
                        <div class="member-card-detail">
                            <span>Status</span>
                            <strong class="status-active">
                                ${member.membershipStatus}
                            </strong>
                        </div>
                        `
                        : ""
                }

            </div>

        </div>
    `;


    // Open complete member details when card is clicked

    card.addEventListener("click", function () {
        openMemberModal(member);
    });


    // Keyboard accessibility

    card.addEventListener("keydown", function (event) {

        if (event.key === "Enter" || event.key === " ") {

            event.preventDefault();

            openMemberModal(member);
        }

    });


    return card;
}


// ============================================================
// CREATE COMMITTEE SECTION
// ============================================================

function createCommitteeSection(title, members) {

    const section = document.createElement("section");

    section.className = "committee-member-section";

    section.innerHTML = `
        <div class="committee-section-heading">

            <h2>${title}</h2>

            <p>${members.length} Members</p>

        </div>

        <div class="committee-grid"></div>
    `;


    const grid = section.querySelector(".committee-grid");


    members.forEach(function (member) {

        grid.appendChild(
            createMemberCard(member)
        );

    });


    return section;
}


