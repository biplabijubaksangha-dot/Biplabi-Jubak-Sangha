// ============================================================
// OPEN MEMBER MODAL
// ============================================================

function openMemberModal(member) {

    createMemberModal();

    const modal =
        document.getElementById(
            "memberDetailsModal"
        );

    if (!modal) {
        return;
    }

    const photo =
        document.getElementById(
            "modal-member-photo"
        );

    const name =
        document.getElementById(
            "modal-member-name"
        );

    const designation =
        document.getElementById(
            "modal-member-designation"
        );

    const father =
        document.getElementById(
            "modal-member-father"
        );

    const registration =
        document.getElementById(
            "modal-member-registration"
        );

    const blood =
        document.getElementById(
            "modal-member-blood"
        );

    const date =
        document.getElementById(
            "modal-member-date"
        );

    const status =
        document.getElementById(
            "modal-member-status"
        );

    const responsibilities =
        document.getElementById(
            "modal-member-responsibilities"
        );


    if (photo) {

        photo.src =
            getMemberPhoto(member.photo);

        photo.alt =
            member.name;

        photo.onerror =
            function () {

                this.onerror = null;

                this.src =
                    "assets/images/logo.png";

            };

    }


    if (name) {
        name.textContent =
            member.name || "Not Updated";
    }

    if (designation) {
        designation.textContent =
            member.designation || "Not Updated";
    }

    if (father) {
        father.textContent =
            member.fatherName || "Not Updated";
    }

    if (registration) {
        registration.textContent =
            member.registrationNo || "Not Updated";
    }

    if (blood) {
        blood.textContent =
            member.bloodGroup || "Not Updated";
    }

    if (date) {
        date.textContent =
            member.dateOfJoining || "Not Updated";
    }

    if (status) {
        status.textContent =
            member.membershipStatus || "Not Updated";
    }

    if (responsibilities) {
        responsibilities.textContent =
            member.responsibilities || "Not Updated";
    }


    modal.classList.add("show");

    document.body.classList.add(
        "member-modal-open"
    );
}


// ============================================================
// CLOSE MEMBER MODAL
// ============================================================

function closeMemberModal() {

    const modal =
        document.getElementById(
            "memberDetailsModal"
        );

    if (!modal) {
        return;
    }

    modal.classList.remove("show");

    document.body.classList.remove(
        "member-modal-open"
    );
}


// ============================================================
// SHOW COMMITTEE
// ============================================================

function showCommittee(type) {

    const home =
        document.getElementById(
            "committee-home"
        );

    const view =
        document.getElementById(
            "committee-view"
        );

    const container =
        document.getElementById(
            "committee-container"
        );

    if (!home || !view || !container) {

        console.error(
            "Committee elements were not found."
        );

        return;
    }


    container.innerHTML = "";


    if (type === "executive") {

        container.appendChild(
            createCommitteeSection(
                "Executive Committee",
                executiveMembers
            )
        );

    }


    if (type === "members") {

        container.appendChild(
            createCommitteeSection(
                "Committee Members",
                committeeMembers
            )
        );

    }


    home.style.display = "none";

    view.style.display = "block";


    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });
}


