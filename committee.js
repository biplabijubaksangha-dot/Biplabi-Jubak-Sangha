// ============================================================
// OPEN MEMBER MODAL
// ============================================================

function openMemberModal(member) {

    createMemberModal();


    const modal =
        document.getElementById("memberDetailsModal");


    if (!modal) {
        return;
    }


    const photo =
        document.getElementById("modal-member-photo");

    const badge =
        document.getElementById("modal-member-badge");

    const name =
        document.getElementById("modal-member-name");

    const father =
        document.getElementById("modal-member-father");

    const registration =
        document.getElementById("modal-member-registration");

    const blood =
        document.getElementById("modal-member-blood");

    const date =
        document.getElementById("modal-member-date");

    const status =
        document.getElementById("modal-member-status");

    const responsibilities =
        document.getElementById("modal-member-responsibilities");


    // ========================================================
    // PHOTO
    // ========================================================

    if (photo) {

        photo.src =
            getMemberPhoto(member.photo);

        photo.alt =
            member.name || "Member Photo";

        photo.onerror = function () {

            this.onerror = null;

            this.src =
                "assets/images/logo.png";

        };

    }


    // ========================================================
    // DESIGNATION
    // ========================================================

    if (badge) {

        badge.textContent =
            member.designation || "Member";

    }


    // ========================================================
    // NAME
    // ========================================================

    if (name) {

        name.textContent =
            member.name || "Not Updated";

    }


    // ========================================================
    // FATHER'S NAME
    // ========================================================

    if (father) {

        father.textContent =
            member.fatherName || "Not Updated";

    }


    // ========================================================
    // REGISTRATION NUMBER
    // ========================================================

    if (registration) {

        registration.textContent =
            member.registrationNo || "Not Updated";

    }


    // ========================================================
    // BLOOD GROUP
    // ========================================================

    if (blood) {

        blood.textContent =
            member.bloodGroup || "Not Updated";

    }


    // ========================================================
    // DATE OF JOINING
    // ========================================================

    if (date) {

        date.textContent =
            member.dateOfJoining || "Not Updated";

    }


    // ========================================================
    // MEMBERSHIP STATUS
    // ========================================================

    if (status) {

        status.textContent =
            member.membershipStatus || "Not Updated";

    }


    // ========================================================
    // RESPONSIBILITIES
    // ========================================================

    if (responsibilities) {

        responsibilities.textContent =
            member.responsibilities || "Not Updated";

    }


    // ========================================================
    // SHOW MODAL
    // ========================================================

    modal.classList.add("active");

    document.body.classList.add("modal-open");

}


// ============================================================
// CLOSE MEMBER MODAL
// ============================================================

function closeMemberModal() {

    const modal =
        document.getElementById("memberDetailsModal");


    if (!modal) {
        return;
    }


    modal.classList.remove("active");

    document.body.classList.remove("modal-open");

}


// ============================================================
// SHOW COMMITTEE
// ============================================================

function showCommittee(type) {

    const home =
        document.getElementById("committee-home");

    const view =
        document.getElementById("committee-view");

    const container =
        document.getElementById("committee-container");


    if (!home || !view || !container) {

        console.error(
            "Committee elements were not found."
        );

        return;
    }


    // CLEAR OLD CONTENT

    container.innerHTML = "";


    // ========================================================
    // EXECUTIVE COMMITTEE
    // ========================================================

    if (type === "executive") {

        container.appendChild(

            createCommitteeSection(
                "Executive Committee",
                executiveMembers
            )

        );

    }


    // ========================================================
    // COMMITTEE MEMBERS
    // ========================================================

    if (type === "members") {

        container.appendChild(

            createCommitteeSection(
                "Committee Members",
                committeeMembers
            )

        );

    }


    // ========================================================
    // HIDE HOME
    // ========================================================

    home.style.display = "none";


    // ========================================================
    // SHOW MEMBER VIEW
    // ========================================================

    view.hidden = false;

    view.style.display = "block";


    // ========================================================
    // SCROLL TO TOP
    // ========================================================

    window.scrollTo({

        top: 0,

        behavior: "smooth"

    });

}


// ============================================================
// RETURN TO COMMITTEE HOME
// ============================================================

function showCommitteeHome() {

    const home =
        document.getElementById("committee-home");

    const view =
        document.getElementById("committee-view");


    if (view) {

        view.hidden = true;

        view.style.display = "none";

    }


    if (home) {

        home.style.display = "block";

    }


    window.scrollTo({

        top: 0,

        behavior: "smooth"

    });

}


