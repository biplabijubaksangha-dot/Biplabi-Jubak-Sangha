// ============================================================
// CREATE MEMBER CARD
// ============================================================

function createMemberCard(member) {

    const card = document.createElement("div");

    card.className = "member-card";

    card.setAttribute("role", "button");

    card.setAttribute("tabindex", "0");

    card.innerHTML = `
        <div class="member-photo">

            <img
                src="${member.photo}"
                alt="${member.name}"
                onerror="this.src='assets/images/logo.png';"
            >

        </div>

        <div class="member-info">

            <h3>
                ${member.name}
            </h3>

            <p class="designation">
                ${member.designation}
            </p>

            <span class="view-details">
                View Details
            </span>

        </div>
    `;

    card.addEventListener("click", () => {

        openMemberModal(member);

    });

    card.addEventListener("keydown", (event) => {

        if (
            event.key === "Enter" ||
            event.key === " "
        ) {

            event.preventDefault();

            openMemberModal(member);

        }

    });

    return card;
}


// ============================================================
// CREATE COMMITTEE SECTION
// ============================================================

function createCommitteeSection(
    title,
    subtitle,
    membersList,
    sectionClass
) {

    const section =
        document.createElement("section");

    section.className =
        `committee-member-section ${sectionClass}`;

    section.innerHTML = `
        <div class="committee-section-heading">

            <span class="section-label">
                BIPLABI JUBAK SANGHA
            </span>

            <h2>
                ${title}
            </h2>

            <p>
                ${subtitle}
            </p>

        </div>

        <div class="committee-grid"></div>
    `;

    const grid =
        section.querySelector(".committee-grid");

    membersList.forEach(member => {

        grid.appendChild(
            createMemberCard(member)
        );

    });

    return section;
}


