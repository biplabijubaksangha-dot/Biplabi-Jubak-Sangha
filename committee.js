// ============================================================
// OPEN MEMBER POPUP
// ============================================================

function openMemberModal(member) {

    const modal =
        document.getElementById(
            "member-details-modal"
        );

    if (!modal) {

        return;

    }

    document.getElementById(
        "modal-member-image"
    ).src =
        member.photo ||
        "assets/images/logo.png";

    document.getElementById(
        "modal-member-image"
    ).alt =
        member.name;

    document.getElementById(
        "modal-member-name"
    ).textContent =
        member.name;

    document.getElementById(
        "modal-member-designation"
    ).textContent =
        member.designation;

    document.getElementById(
        "modal-member-registration"
    ).textContent =
        member.registrationNo ||
        "Not Updated";

    document.getElementById(
        "modal-member-blood"
    ).textContent =
        member.bloodGroup ||
        "Not Updated";

    document.getElementById(
        "modal-member-responsibilities"
    ).textContent =
        member.responsibilities ||
        "Not Updated";

    modal.classList.add("active");

    document.body.classList.add(
        "modal-open"
    );

}


// ============================================================
// CLOSE MEMBER POPUP
// ============================================================

function closeMemberModal() {

    const modal =
        document.getElementById(
            "member-details-modal"
        );

    if (!modal) {

        return;

    }

    modal.classList.remove("active");

    document.body.classList.remove(
        "modal-open"
    );

}


// ============================================================
// SHOW EXECUTIVE / COMMITTEE LIST
// ============================================================

function showCommittee(type) {

    const home =
        document.getElementById(
            "committee-home"
        );

    const view =
        document.getElementById(
            "committee-view"
        );

    const container =
        document.getElementById(
            "committee-container"
        );

    if (
        !home ||
        !view ||
        !container
    ) {

        return;

    }

    container.innerHTML = "";


    // ================= EXECUTIVE =================

    if (type === "executive") {

        const section =
            createCommitteeSection(

                "Executive Committee Members",

                "Our 13-member Executive Committee provides leadership, coordination and direction for Biplabi Jubak Sangha.",

                executiveMembers,

                "executive-committee-section"

            );

        container.appendChild(section);

    }


    // ================= COMMITTEE MEMBERS =================

    if (type === "members") {

        const section =
            createCommitteeSection(

                "Committee Members",

                "Our committee members support organisational programmes, community service and development activities.",

                committeeMembers,

                "committee-members-section"

            );

        container.appendChild(section);

    }


    home.hidden = true;

    view.hidden = false;


    window.scrollTo({

        top:
            view.offsetTop - 30,

        behavior:
            "smooth"

    });

}


// ============================================================
// BACK TO COMMITTEE HOME
// ============================================================

function showCommitteeHome() {

    const home =
        document.getElementById(
            "committee-home"
        );

    const view =
        document.getElementById(
            "committee-view"
        );

    if (!home || !view) {

        return;

    }

    view.hidden = true;

    home.hidden = false;


    window.scrollTo({

        top:
            home.offsetTop - 30,

        behavior:
            "smooth"

    });

}


// ============================================================
// ESC KEY CLOSES POPUP
// ============================================================

document.addEventListener(
    "keydown",
    event => {

        if (

            event.key === "Escape" &&

            document
                .getElementById(
                    "member-details-modal"
                )
                ?.classList.contains(
                    "active"
                )

        ) {

            closeMemberModal();

        }

    }
);


// ============================================================
// LOAD PAGE
// ============================================================

function loadCommittee() {

    createMemberModal();


    const executiveButton =
        document.querySelector(
            '[data-section="executive"]'
        );


    const membersButton =
        document.querySelector(
            '[data-section="members"]'
        );


    const backButton =
        document.getElementById(
            "committee-back"
        );


    // EXECUTIVE BUTTON

    if (executiveButton) {

        executiveButton.addEventListener(
            "click",
            () => {

                showCommittee(
                    "executive"
                );

            }
        );

    }


    // COMMITTEE MEMBERS BUTTON

    if (membersButton) {

        membersButton.addEventListener(
            "click",
            () => {

                showCommittee(
                    "members"
                );

            }
        );

    }


    // BACK BUTTON

    if (backButton) {

        backButton.addEventListener(
            "click",
            showCommitteeHome
        );

    }

}


// ============================================================
// START
// ============================================================

if (
    document.readyState === "loading"
) {

    document.addEventListener(
        "DOMContentLoaded",
        loadCommittee
    );

} else {

    loadCommittee();

}