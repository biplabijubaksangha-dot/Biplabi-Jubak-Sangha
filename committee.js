// ============================================================
// PHOTO PATH
// ============================================================

function getMemberPhoto(photo) {

    if (!photo) {
        return "assets/images/logo.png";
    }

    return photo;

}


// ============================================================
// CREATE MEMBER CARD
// ============================================================

function createMemberCard(member) {

    const card = document.createElement("div");

    card.className = "member-card";

    card.innerHTML = `
        <div class="member-photo">
            <img
                src="${getMemberPhoto(member.photo)}"
                alt="${member.name}"
                loading="lazy"
                onerror="this.onerror=null;this.src='assets/images/logo.png';"
            >
        </div>

        <div class="member-info">

            <h3>${member.name}</h3>

            <p class="member-designation">
                ${member.designation}
            </p>

            <button
                type="button"
                class="view-details-btn"
            >
                View Details
            </button>

        </div>
    `;

    const button =
        card.querySelector(".view-details-btn");

    if (button) {
        button.addEventListener("click", function () {
            openMemberModal(member);
        });
    }

    return card;
}


// ============================================================
// CREATE COMMITTEE SECTION
// ============================================================

function createCommitteeSection(title, members) {

    const section =
        document.createElement("section");

    section.className =
        "committee-members-section";

    section.innerHTML = `
        <div class="committee-section-heading">

            <h2>${title}</h2>

            <p>
                ${members.length} Members
            </p>

        </div>

        <div class="members-grid"></div>
    `;

    const grid =
        section.querySelector(".members-grid");

    members.forEach(function (member) {

        grid.appendChild(
            createMemberCard(member)
        );

    });

    return section;
}


